-- Item booking uses a row lock on items before checking overlapping capacity.
-- Each user/key pair identifies one logical request across network retries.
CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_seq BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE,
    applicant_id BIGINT NOT NULL REFERENCES users(id),
    resource_type VARCHAR(20) NOT NULL CHECK (resource_type = 'ITEM'),
    item_id BIGINT NOT NULL REFERENCES items(id),
    start_at TIMESTAMPTZ NOT NULL,
    end_at TIMESTAMPTZ NOT NULL,
    purpose VARCHAR(300) NOT NULL CHECK (length(btrim(purpose)) > 0),
    quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
    status VARCHAR(30) NOT NULL CHECK (status IN ('PENDING_APPROVAL', 'CONFIRMED', 'REJECTED', 'CANCELLED', 'EXPIRED')),
    idempotency_key VARCHAR(100) NOT NULL,
    payload_hash VARCHAR(64) NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT reservation_time_order CHECK (end_at > start_at),
    CONSTRAINT unique_applicant_request UNIQUE (applicant_id, idempotency_key)
);
CREATE INDEX idx_reservations_item_slot ON reservations(item_id, start_at, end_at)
    WHERE status = 'CONFIRMED';
CREATE INDEX idx_reservations_applicant ON reservations(applicant_id, id DESC);
