-- Item handover is independent from the reservation approval state.
-- A confirmed reservation keeps status=CONFIRMED while handover_status tracks
-- pickup, return submission and verification.
ALTER TABLE reservations
    ADD COLUMN handover_status VARCHAR(30),
    ADD COLUMN picked_up_at TIMESTAMPTZ,
    ADD COLUMN last_return_reason VARCHAR(200),
    ADD CONSTRAINT reservations_handover_status_check CHECK (
        handover_status IS NULL OR handover_status IN (
            'NOT_PICKED_UP', 'CHECKED_OUT', 'RETURN_SUBMITTED',
            'RETURN_REJECTED', 'COMPLETED'
        )
    );

UPDATE reservations
SET handover_status = 'NOT_PICKED_UP'
WHERE resource_type = 'ITEM' AND status = 'CONFIRMED'
  AND end_at > CURRENT_TIMESTAMP;

CREATE TABLE reservation_units (
    reservation_id BIGINT NOT NULL REFERENCES reservations(id) ON DELETE CASCADE,
    unit_id BIGINT NOT NULL REFERENCES item_units(id),
    bound_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (reservation_id, unit_id)
);
CREATE INDEX idx_reservation_units_unit ON reservation_units(unit_id, reservation_id);

CREATE TABLE return_submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL REFERENCES reservations(id) ON DELETE CASCADE,
    attempt_no INTEGER NOT NULL CHECK (attempt_no > 0),
    remark VARCHAR(300) NOT NULL DEFAULT '',
    status VARCHAR(30) NOT NULL CHECK (
        status IN ('RETURN_SUBMITTED', 'RETURN_REJECTED', 'COMPLETED')
    ),
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_by BIGINT REFERENCES users(id),
    review_reason VARCHAR(200),
    reviewed_at TIMESTAMPTZ,
    CONSTRAINT unique_return_attempt UNIQUE (reservation_id, attempt_no)
);
CREATE INDEX idx_return_submissions_queue
    ON return_submissions(status, submitted_at, id);

CREATE TABLE return_photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL REFERENCES return_submissions(id) ON DELETE CASCADE,
    storage_key VARCHAR(500) NOT NULL UNIQUE CHECK (length(btrim(storage_key)) > 0),
    file_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(30) NOT NULL CHECK (
        content_type IN ('image/jpeg', 'image/png', 'image/webp')
    ),
    size_bytes BIGINT NOT NULL CHECK (size_bytes > 0),
    width INTEGER NOT NULL CHECK (width > 0),
    height INTEGER NOT NULL CHECK (height > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_return_photos_submission ON return_photos(submission_id, id);

CREATE TABLE reservation_action_idempotency (
    actor_user_id BIGINT NOT NULL REFERENCES users(id),
    action VARCHAR(40) NOT NULL,
    reservation_id BIGINT NOT NULL REFERENCES reservations(id) ON DELETE CASCADE,
    request_key VARCHAR(200) NOT NULL,
    payload_hash VARCHAR(64) NOT NULL,
    result_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (actor_user_id, action, request_key)
);
