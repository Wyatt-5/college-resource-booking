ALTER TABLE reservations DROP CONSTRAINT reservations_decision_check;
ALTER TABLE reservations ADD CONSTRAINT reservations_decision_check
    CHECK (decision IS NULL OR decision IN ('APPROVED','REJECTED','AUTO_CONFIRMED','EXPIRED'));

CREATE TABLE background_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(30) NOT NULL CHECK (type IN ('EXPIRE_PENDING','REMIND_OVERDUE')),
    reservation_id BIGINT NOT NULL REFERENCES reservations(id),
    state VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (state IN ('PENDING','LEASED','SUCCEEDED','SKIPPED','FAILED')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    available_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lease_token VARCHAR(36),
    lease_until TIMESTAMPTZ,
    last_error VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    UNIQUE (type, reservation_id)
);
CREATE INDEX background_tasks_queue ON background_tasks(state, available_at, id);
CREATE INDEX reservations_pending_start ON reservations(start_at) WHERE status='PENDING_APPROVAL';
CREATE INDEX reservations_overdue_end ON reservations(end_at)
    WHERE status='CONFIRMED' AND handover_status IN ('CHECKED_OUT','RETURN_REJECTED');

CREATE TABLE return_reminders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL UNIQUE REFERENCES reservations(id),
    message VARCHAR(500) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
