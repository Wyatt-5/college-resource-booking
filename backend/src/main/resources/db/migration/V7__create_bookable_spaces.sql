CREATE TABLE bookable_space_images (
    space_id BIGINT PRIMARY KEY REFERENCES bookable_spaces(id) ON DELETE CASCADE,
    content BYTEA NOT NULL,
    content_type VARCHAR(30) NOT NULL
);

