ALTER TABLE reservations ADD CONSTRAINT reservation_resource_type
    CHECK ((resource_type = 'ITEM' AND item_id IS NOT NULL AND space_id IS NULL)
        OR (resource_type = 'SPACE' AND item_id IS NULL AND space_id IS NOT NULL));
CREATE INDEX idx_reservations_space_slot ON reservations(space_id, start_at, end_at)
    WHERE status IN ('PENDING_APPROVAL', 'CONFIRMED');
