CREATE TABLE items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id BIGINT NOT NULL REFERENCES locations(id),
    name VARCHAR(100) NOT NULL CHECK (length(btrim(name)) > 0),
    description VARCHAR(4000) NOT NULL DEFAULT '',
    is_valuable BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(20) NOT NULL DEFAULT 'INACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    max_advance_days INTEGER CHECK (max_advance_days > 0),
    max_borrow_hours INTEGER CHECK (max_borrow_hours > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_items_location ON items(location_id);

CREATE TABLE item_units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES items(id),
    unit_code VARCHAR(100) NOT NULL UNIQUE CHECK (length(btrim(unit_code)) > 0),
    status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE'
        CHECK (status IN ('AVAILABLE', 'CHECKED_OUT', 'RETURN_SUBMITTED', 'MAINTENANCE', 'INACTIVE', 'LOST')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_item_units_item_status ON item_units(item_id, status);

-- Storage keys remain server-side; future image access must check permissions.
CREATE TABLE item_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES items(id),
    storage_key VARCHAR(500) NOT NULL UNIQUE CHECK (length(btrim(storage_key)) > 0),
    content_type VARCHAR(30) NOT NULL CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
    size_bytes BIGINT NOT NULL CHECK (size_bytes > 0),
    width INTEGER NOT NULL CHECK (width > 0),
    height INTEGER NOT NULL CHECK (height > 0),
    sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_item_images_item_sort ON item_images(item_id, sort_order, id);
